CREATE TABLE users (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username      text NOT NULL UNIQUE,
    email         text NOT NULL,
    country       text NOT NULL,
    age           integer NOT NULL,
    status        text NOT NULL,
    created_at    timestamptz NOT NULL,
    last_login_at timestamptz
);

