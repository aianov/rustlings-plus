#![allow(clippy::needless_late_init)]

fn main() {
    // В Rust нельзя читать неинициализированные переменные!
    // Поэтому сначала нужно присвоить значение.
    let x: i32 = 42;

    println!("Число {x}");

    // Объявить переменную и инициализировать её позже можно.
    // Но использовать её до инициализации нельзя.
    let y: i32;
    y = 42;
    println!("Число {y}");
}
