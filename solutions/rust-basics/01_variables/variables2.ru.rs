fn main() {
    // Проще всего исправить ошибку компилятора, инициализировав
    // переменную `x`. Если присвоить ей целое число, Rust выведет тип
    // `i32`: это тип целых чисел по умолчанию.
    let x = 42;

    // Но можно задать тип, отличный от `i32` по умолчанию,
    // добавив аннотацию типа:
    // let x: u8 = 42;

    if x == 10 {
        println!("x равен десяти!");
    } else {
        println!("x не равен десяти!");
    }
}
